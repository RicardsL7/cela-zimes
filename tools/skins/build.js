// Builds the Garage skins: node tools/skins/build.js
//   • skins-art.js — browser bundle of chars.js + costumes.js + sets.js: skinArtSvg(id) draws a non-fox skin
//     in the browser (70 designs; no image files to download)
//   • skins/<id>.svg and skins/<id>-map.svg for the 8 foxes (drawn by skins.js)
//   • the catalogue block in skins.js (SKINS_DEFAULT)
//   • supabase/coins-3-skins.sql (rows for public.skins)
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const { draw, CHARS } = require('./chars.js');
const { SETS } = require('./sets.js');
const sk = require(path.join(ROOT, 'skins.js'));

const PRICE = { common: [200, 250, 300], rare: [400, 450, 500], epic: [650, 750], mythic: [1200, 1500] };
const ORDER = ['common', 'rare', 'epic', 'mythic'];
const FOXES = [['chef', 'Pavārs', 200], ['cowboy', 'Kovbojs', 300], ['pilot', 'Pilots', 350], ['viking', 'Vikings', 400],
  ['ninja', 'Ninja', 450], ['wizard', 'Burvis', 500], ['rally', 'Rallijs', 600], ['rainbow', 'Varavīksne', 800]];
const LV = { 'ā': 'a', 'č': 'c', 'ē': 'e', 'ģ': 'g', 'ī': 'i', 'ķ': 'k', 'ļ': 'l', 'ņ': 'n', 'š': 's', 'ū': 'u', 'ž': 'z' };
const slug = s => s.toLowerCase().replace(/[āčēģīķļņšūž]/g, c => LV[c]).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const all = FOXES.map(([id, name, price], i) => ({ id, name, price, character: 'fox', sort: i + 1, svg: sk.skinShopSvg(id) }));
let sort = 100;
for (const [ch, set] of Object.entries(SETS)) {
  const seen = { common: 0, rare: 0, epic: 0, mythic: 0 };
  for (const r of ORDER) for (const c of set.filter(x => x.rar === r)) {
    all.push({ id: `${ch}-${slug(c.name)}`, name: c.name, price: PRICE[r][seen[r]++], character: ch, sort: ++sort, svg: draw(ch, c), idx: set.indexOf(c) });
  }
}
if (new Set(all.map(s => s.id)).size !== all.length) throw new Error('duplicate skin id');

fs.mkdirSync(path.join(ROOT, 'skins'), { recursive: true });
for (const s of all.filter(x => x.character === 'fox')) {
  fs.writeFileSync(path.join(ROOT, 'skins', s.id + '.svg'), s.svg);
  fs.writeFileSync(path.join(ROOT, 'skins', s.id + '-map.svg'), sk.skinMapFromShop(s.svg));
}

// Browser bundle: the three modules in one scope, without require / module.exports.
const strip = f => fs.readFileSync(path.join(__dirname, f), 'utf8')
  .replace(/^const \{[^}]*\} = require\([^)]*\);\n/m, '').replace(/^module\.exports = [^\n]*\n?/m, '');
const ids = all.filter(x => x.character !== 'fox').map(x => [x.id, x.character, x.idx]);
const bundle = `// Ceļa Zīmes — Garāža: the 7 extra characters (70 designs), drawn in the browser.
// GENERATED by tools/skins/build.js from tools/skins/{costumes,sets,chars}.js — do not edit by hand.
(function () {
${strip('costumes.js')}
${strip('sets.js')}
${strip('chars.js')}
const IDS = ${JSON.stringify(Object.fromEntries(ids.map(([id, ch, i]) => [id, [ch, i]])))};
// SVG of a skin by id ('' if unknown). Same output as the build (used for the shop and the map).
function skinArtSvg(id) {
  const e = IDS[id];
  return e ? draw(e[0], SETS[e[0]][e[1]]) : '';
}
const root = typeof window !== 'undefined' ? window : globalThis;
root.skinArtSvg = skinArtSvg;
if (typeof module !== 'undefined') module.exports = { skinArtSvg, IDS };
})();
`;
fs.writeFileSync(path.join(ROOT, 'skins-art.js'), bundle);

// skins.js catalogue block
const js = path.join(ROOT, 'skins.js');
const src = fs.readFileSync(js, 'utf8');
const block = '// BEGIN SKINS CATALOG — generated by tools/skins/build.js, do not edit by hand\nconst SKINS_DEFAULT = [\n' +
  all.map(s => `  { id: '${s.id}', name: '${s.name}', price: ${s.price}, character: '${s.character}' },`).join('\n') +
  '\n].map(s => ({ ...s, rarity: skinRarity(s.price) }));\n// END SKINS CATALOG';
fs.writeFileSync(js, src.replace(/\/\/ BEGIN SKINS CATALOG[\s\S]*?\/\/ END SKINS CATALOG/, block));

// SQL
const q = s => "'" + s.replace(/'/g, "''") + "'";
const sql = `-- Ceļa Zīmes — Garāža: 7 more characters × 10 designs, the "mythic" tier and a character filter.
-- GENERATED by tools/skins/build.js — do not edit by hand.
--
-- HOW TO RUN: Supabase → SQL Editor → New query → paste this whole file → Run. Run AFTER coins-1.sql.
-- Safe to re-run. Owned / equipped skins are kept. Images of the new characters are drawn in the app (skins-art.js).

-- Which character a skin belongs to (fox, bear, cat, panda, penguin, owl, bunny, raccoon).
alter table public.skins add column if not exists animal text not null default 'fox';
-- Rarity by price: mythic ≥ 1000, epic ≥ 600, rare ≥ 400, otherwise common.
alter table public.skins drop column if exists rarity;
alter table public.skins add column rarity text generated always as (
  case when price >= 1000 then 'mythic' when price >= 600 then 'epic' when price >= 400 then 'rare' else 'common' end) stored;

insert into public.skins (id, name, price, animal, shop_image, map_image, sort) values
${all.map(s => `  (${q(s.id)}, ${q(s.name)}, ${s.price}, ${q(s.character)}, ${s.character === 'fox' ? q('skins/' + s.id + '.svg') + ', ' + q('skins/' + s.id + '-map.svg') : q('skins-art.js#' + s.id) + ', ' + q('skins-art.js#' + s.id)}, ${s.sort})`).join(',\n')}
on conflict (id) do update set name = excluded.name, price = excluded.price, animal = excluded.animal,
  shop_image = excluded.shop_image, map_image = excluded.map_image, sort = excluded.sort;

drop function if exists public.skins_list();
create function public.skins_list() returns table (id text, name text, price int, rarity text, animal text,
    shop_image text, map_image text)
  language sql stable security definer set search_path = public as
$$ select id, name, price, rarity, animal, shop_image, map_image from skins where active order by price, sort $$;
revoke all on function public.skins_list() from public;
grant execute on function public.skins_list() to anon, authenticated;
`;
fs.writeFileSync(path.join(ROOT, 'supabase', 'coins-3-skins.sql'), sql);
console.log(`${all.length} skins (${Object.keys(CHARS).length + 1} characters)`);
